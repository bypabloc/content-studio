/** Nombre de un ícono del set. */
export type IconName = keyof typeof ICONS

/** Nombres disponibles (para tests y catálogos). */
export const ICON_NAMES = Object.keys(ICONS) as IconName[]

type Props = { name: IconName; className?: string; label?: string }

/**
 * Ícono de lucide-react (24×24, trazo `currentColor`). Sin `label` es
 * decorativo y queda oculto a lectores de pantalla; con `label` es una
 * imagen con nombre accesible.
 *
 * @author Pablo Contreras
 * @since 2026/09/27
 * @since 2026/11/19
 */
export function UIIcon({ name, className = 'size-5', label }: Props): React.JSX.Element {
  const Icon = ICONS[name]
  return (
    <Icon
      className={`shrink-0 ${className}`}
      focusable="false"
      {...(label ? { role: 'img', 'aria-label': label, 'aria-hidden': false } : { 'aria-hidden': true })}
    />
  )
}
